import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

export async function GET() {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const { data, error } = await supabase
    .from("profiles")
    .select("reader_dark_mode")
    .eq("id", user.id)
    .maybeSingle();

  if (error) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }

  return NextResponse.json({ darkMode: data?.reader_dark_mode ?? false });
}

export async function POST(request: Request) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const darkMode =
    typeof body === "object" &&
    body !== null &&
    "darkMode" in body &&
    typeof (body as { darkMode: unknown }).darkMode === "boolean"
      ? (body as { darkMode: boolean }).darkMode
      : null;

  if (darkMode === null) {
    return NextResponse.json({ error: "darkMode boolean is required" }, { status: 400 });
  }

  const { error } = await supabase
    .from("profiles")
    .update({
      reader_dark_mode: darkMode,
      reader_preferences_updated_at: new Date().toISOString(),
    })
    .eq("id", user.id);

  if (error) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }

  return NextResponse.json({ ok: true, darkMode });
}
